export function buildInitialAffiliateCatalog(now = new Date()): Omit<AffiliateProduct, 'scoreBreakdown'>[] {
  const nowIso = now.toISOString();
  return RAW_SEED_PRODUCTS.map((raw) => {
    const hourlyHistory = generateHourlySeries(raw.baseHourlySold, raw.priceVnd, now);
    const soldLastHour = hourlyHistory[hourlyHistory.length - 1]?.sold ?? raw.baseHourlySold;
    const soldToday = hourlyHistory.reduce((acc, p) => acc + p.sold, 0);
    const dailyHistory = generateDailySeries(
      soldToday,
      raw.priceVnd,
      1 + raw.dailyGrowthPct / 220,
      now
    );
    // Align today's entry in dailyHistory with 24h rolling soldToday
    if (dailyHistory.length > 0) {
      dailyHistory[dailyHistory.length - 1] = {
        date: nowIso.slice(0, 10),
        sold: soldToday,
        revenueVnd: soldToday * raw.priceVnd,
        affiliateOrders: Math.round(soldToday * 0.45),
      };
    }
    const sold7d = dailyHistory.reduce((acc, d) => acc + d.sold, 0);
    const sold30d = Math.round(sold7d * 3.85);
    const discountPct = Math.max(
      0,
      Math.round(((raw.originalPriceVnd - raw.priceVnd) / raw.originalPriceVnd) * 100)
    );
    const estimatedCommissionVnd = Math.round((raw.priceVnd * raw.commissionRatePct) / 100);

    const reputableSellers: ReputableSeller[] = raw.sellers
      .map((s) => {
        const shopSearchUrl =
          s.platform === 'shopee'
            ? buildShopeeSearchUrl(`${raw.name.split(' ').slice(0, 5).join(' ')} ${s.shopName.split(' ')[0]}`)
            : buildTiktokSearchUrl(`${raw.name.split(' ').slice(0, 5).join(' ')} ${s.shopName.split(' ')[0]}`);
        return {
          ...s,
          shopSearchUrl,
          trustScore: computeSellerTrustScore(s),
        };
      })
      .sort((a, b) => b.trustScore - a.trustScore);

    const shortKeyword = raw.name.split(' ').slice(0, 6).join(' ');

    return {
      id: raw.id,
      name: raw.name,
      slug: raw.id,
      category: raw.category,
      subcategory: raw.subcategory,
      platforms: raw.platforms,
      primaryPlatform: raw.primaryPlatform,
      seasons: raw.seasons,
      thumbnailEmoji: raw.thumbnailEmoji,
      thumbnailGradient: raw.thumbnailGradient,
      priceVnd: raw.priceVnd,
      originalPriceVnd: raw.originalPriceVnd,
      discountPct,
      commissionRatePct: raw.commissionRatePct,
      estimatedCommissionVnd,
      freeSampleAvailable: raw.freeSampleAvailable,
      hasExtraBonus: raw.hasExtraBonus,
      soldLastHour,
      hourlyGrowthPct: raw.hourlyGrowthPct,
      soldToday,
      dailyGrowthPct: raw.dailyGrowthPct,
      sold7d,
      sold30d,
      revenueTodayVnd: soldToday * raw.priceVnd,
      conversionRatePct: raw.conversionRatePct,
      creatorCount7d: raw.creatorCount7d,
      competitionLevel: raw.competitionLevel,
      rating: raw.rating,
      buyerEvidence: raw.buyerEvidence,
      reputableSellers,
      hourlyHistory,
      dailyHistory,
      viralHooks: raw.viralHooks,
      videoPrompt916: raw.videoPrompt916,
      productSearchUrlShopee: buildShopeeSearchUrl(shortKeyword),
      productSearchUrlTiktok: buildTiktokSearchUrl(shortKeyword),
      source: 'seed_seasonal',
      lastHourlySyncAt: nowIso,
      lastDailySyncAt: nowIso,
    };
  });
}
