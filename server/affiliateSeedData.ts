export function detectSeasonForDate(date = new Date()): SeasonId {
  const month = date.getMonth() + 1; // 1..12
  if (month === 11 || month === 12) return 'winter_festival';
  if (month === 1 || month === 2) return 'tet_holiday';
  if (month === 3) return 'rainy_humid';
  if (month >= 4 && month <= 7) return 'summer_travel';
  if (month === 8 || month === 9) return 'back_to_school';
  return 'mega_sale_year_end';
}

