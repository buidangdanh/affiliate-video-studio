export function generateHourlySeries(
  baseHourlySold: number,
  priceVnd: number,
  now = new Date()
): HourlyDataPoint[] {
  const points: HourlyDataPoint[] = [];
  // E-commerce hourly curve multiplier (peaks at 12:00-13:00 and 20:00-22:00)
  const hourCurve: Record<number, number> = {
    0: 0.72,
    1: 0.42,
    2: 0.25,
    3: 0.18,
    4: 0.16,
    5: 0.24,
    6: 0.45,
    7: 0.68,
    8: 0.85,
    9: 0.96,
    10: 1.08,
    11: 1.28,
    12: 1.52,
    13: 1.34,
    14: 1.02,
    15: 0.98,
    16: 1.05,
    17: 1.12,
    18: 1.18,
    19: 1.35,
    20: 1.68,
    21: 1.82,
    22: 1.55,
    23: 1.12,
  };

  for (let i = 23; i >= 0; i--) {
    const dt = new Date(now.getTime() - i * 3600_000);
    const hr = dt.getHours();
    const mult = hourCurve[hr] ?? 1.0;
    // Deterministic slight wave based on hour + base
    const jitter = 0.9 + (((hr * 7 + baseHourlySold) % 21) / 100);
    const sold = Math.max(3, Math.round(baseHourlySold * mult * jitter));
    points.push({
      hourLabel: `${String(hr).padStart(2, '0')}:00`,
      timestamp: dt.toISOString(),
      sold,
      revenueVnd: sold * priceVnd,
      liveViewers: Math.round(sold * (5.2 + ((hr % 5) * 0.6))),
    });
  }
  return points;
}

export function generateDailySeries(
  baseDailySold: number,
  priceVnd: number,
  growthTrend = 1.04,
  now = new Date()
): DailyDataPoint[] {
  const points: DailyDataPoint[] = [];
  for (let d = 6; d >= 0; d--) {
    const dt = new Date(now.getTime() - d * 86_400_000);
    const dateStr = dt.toISOString().slice(0, 10);
    const factor = Math.pow(growthTrend, 6 - d) * (0.92 + (((d * 13 + baseDailySold) % 17) / 100));
    const sold = Math.max(25, Math.round(baseDailySold * factor * 0.85));
    points.push({
      date: dateStr,
      sold,
      revenueVnd: sold * priceVnd,
      affiliateOrders: Math.round(sold * 0.42),
    });
  }
  return points;
}

export function computeSellerTrustScore(
  s: Pick<
    ReputableSeller,
    'badge' | 'rating' | 'onTimeShipPct' | 'responseRatePct' | 'returnRatePct'
  >
): number {
  const badgeBonus: Record<ReputableSeller['badge'], number> = {
    'Shopee Mall': 26,
    'TikTok Shop Mall': 26,
    'Yêu Thích+': 21,
    'Star Shop': 20,
    'Yêu Thích': 16,
    'Shop Uy Tín': 13,
  };
  const ratingPts = Math.min(28, Math.max(0, (s.rating - 4.2) * 35)); // 5.0 -> 28
  const shipPts = Math.min(20, Math.max(0, (s.onTimeShipPct - 85) * 1.35));
  const responsePts = Math.min(14, Math.max(0, (s.responseRatePct - 75) * 0.56));
  const lowReturnPts = Math.min(12, Math.max(0, (6 - s.returnRatePct) * 2.4));
  const raw = (badgeBonus[s.badge] || 14) + ratingPts + shipPts + responsePts + lowReturnPts;
  return Math.min(99, Math.max(60, Math.round(raw)));
}

